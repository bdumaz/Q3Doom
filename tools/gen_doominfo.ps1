# Generates src/libdoom/doom_info.h and doom_info.c from id Software's
# linuxdoom-1.10 tables (info.h, info.c, sounds.h, sounds.c, p_mobj.h; GPLv2).
# The data is kept as is; action function pointers become doom_action_t values
# so the tables are plain data usable by the game, cgame and tools.
#
#   powershell -File tools/gen_doominfo.ps1
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root "external\DOOM\linuxdoom-1.10"
$out = Join-Path $root "src\libdoom"

function ReadText($name) { [IO.File]::ReadAllText((Join-Path $src $name)) -replace "`r`n", "`n" }

# returns the "typedef enum { ... } <name>;" block for an enum
function EnumBlock($text, $name) {
    $m = [regex]::Match($text, "typedef enum\s*\{[^}]*\}\s*$name\s*;", 'Singleline')
    if (-not $m.Success) { throw "enum $name not found" }
    $m.Value
}

# returns the initializer body of "<decl> = { ... };"
function InitializerBody($text, $declPattern) {
    $m = [regex]::Match($text, "$declPattern\s*=\s*\{", 'Singleline')
    if (-not $m.Success) { throw "initializer $declPattern not found" }
    $start = $m.Index + $m.Length
    $depth = 1
    for ($i = $start; $i -lt $text.Length; $i++) {
        if ($text[$i] -eq '{') { $depth++ }
        elseif ($text[$i] -eq '}') { $depth--; if ($depth -eq 0) { return $text.Substring($start, $i - $start) } }
    }
    throw "unterminated initializer $declPattern"
}

$infoH = ReadText "info.h"
$infoC = ReadText "info.c"
$soundsH = ReadText "sounds.h"
$soundsC = ReadText "sounds.c"
$mobjH = ReadText "p_mobj.h"

$sprEnum = EnumBlock $infoH "spritenum_t"
$stateEnum = EnumBlock $infoH "statenum_t"
$mobjEnum = EnumBlock $infoH "mobjtype_t"
$sfxEnum = EnumBlock $soundsH "sfxenum_t"
$flagEnum = EnumBlock $mobjH "mobjflag_t"

$sprBody = InitializerBody $infoC 'char \*sprnames\[NUMSPRITES\]'
$statesBody = InitializerBody $infoC 'state_t\s+states\[NUMSTATES\]'
$mobjBody = InitializerBody $infoC 'mobjinfo_t mobjinfo\[NUMMOBJTYPES\]'
$sfxBody = InitializerBody $soundsC 'sfxinfo_t S_sfx\[\]'

# action functions, in order of first use
$actions = New-Object System.Collections.Generic.List[string]
foreach ($m in [regex]::Matches($statesBody, '\{(A_\w+)\}')) {
    if (-not $actions.Contains($m.Groups[1].Value)) { $actions.Add($m.Groups[1].Value) }
}
$statesBody = [regex]::Replace($statesBody, '\{A_(\w+)\}', 'ACT_$1')
$statesBody = $statesBody.Replace('{NULL}', 'ACT_NULL')

# sound effect names: the first string of every S_sfx entry
$sfxNames = [regex]::Matches($sfxBody, '\{\s*"(\w+)"') | ForEach-Object { $_.Groups[1].Value }

$header = @"
/*
===========================================================================
libdoom - Doom thing, state, sprite and sound tables

GENERATED by tools/gen_doominfo.ps1 from id Software's linuxdoom-1.10
(info.h, info.c, sounds.h, sounds.c, p_mobj.h), GPLv2. Do not edit.
Action function pointers are replaced by doom_action_t values.
===========================================================================
*/
#ifndef LIBDOOM_INFO_H
#define LIBDOOM_INFO_H

#define DOOM_FRACUNIT		65536
#define DOOM_FF_FULLBRIGHT	0x8000		// state frame flag
#define DOOM_FF_FRAMEMASK	0x7fff

$sprEnum

$stateEnum

$mobjEnum

$sfxEnum

$flagEnum

typedef enum {
	ACT_NULL,
$(($actions | ForEach-Object { "`tACT_$($_.Substring(2)),"}) -join "`n")
	NUMACTIONS
} doom_action_t;

typedef struct {
	spritenum_t		sprite;
	int				frame;			// letter index, | DOOM_FF_FULLBRIGHT
	int				tics;			// -1 = forever
	doom_action_t	action;
	statenum_t		nextstate;
	int				misc1, misc2;
} doom_state_t;

typedef struct {
	int		doomednum;
	int		spawnstate;
	int		spawnhealth;
	int		seestate;
	int		seesound;
	int		reactiontime;
	int		attacksound;
	int		painstate;
	int		painchance;
	int		painsound;
	int		meleestate;
	int		missilestate;
	int		deathstate;
	int		xdeathstate;
	int		deathsound;
	int		speed;
	int		radius;			// fixed point (DOOM_FRACUNIT)
	int		height;			// fixed point
	int		mass;
	int		damage;
	int		activesound;
	int		flags;			// mobjflag_t
	int		raisestate;
} doom_mobjinfo_t;

extern const doom_state_t		doom_states[NUMSTATES];
extern const char *const		doom_sprnames[NUMSPRITES];
extern const doom_mobjinfo_t	doom_mobjinfo[NUMMOBJTYPES];
extern const char *const		doom_sfxnames[NUMSFX];		// lump is "DS" + name
extern const char *const		doom_actionnames[NUMACTIONS];

// mobj type for a map thing number (doomednum), or -1
int		doom_mobjtype_for_ednum( int doomednum );

#endif
"@

$source = @"
/*
===========================================================================
libdoom - Doom thing, state, sprite and sound tables

GENERATED by tools/gen_doominfo.ps1 from id Software's linuxdoom-1.10
(info.c, sounds.c), GPLv2. Do not edit.
===========================================================================
*/
#include "doom_info.h"

#include <stddef.h>

#define FRACUNIT	DOOM_FRACUNIT

const char *const doom_sprnames[NUMSPRITES] = {$sprBody};

const doom_state_t doom_states[NUMSTATES] = {$statesBody};

const doom_mobjinfo_t doom_mobjinfo[NUMMOBJTYPES] = {$mobjBody};

const char *const doom_sfxnames[NUMSFX] = {
$(($sfxNames | ForEach-Object { "`t`"$_`"," }) -join "`n")
};

const char *const doom_actionnames[NUMACTIONS] = {
	"NULL",
$(($actions | ForEach-Object { "`t`"$_`"," }) -join "`n")
};

int doom_mobjtype_for_ednum( int doomednum ) {
	int		i;

	for ( i = 0 ; i < NUMMOBJTYPES ; i++ ) {
		if ( doom_mobjinfo[i].doomednum == doomednum ) {
			return i;
		}
	}
	return -1;
}
"@

[IO.File]::WriteAllText((Join-Path $out "doom_info.h"), $header.Replace("`r`n", "`n"))
[IO.File]::WriteAllText((Join-Path $out "doom_info.c"), $source.Replace("`r`n", "`n"))
Write-Host "doom_info: $($actions.Count) actions, $($sfxNames.Count) sounds"
